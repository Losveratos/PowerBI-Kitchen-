/** fill {0} {1} … placeholders */
export function fillArgs(s: string, args: (string | number)[]): string {
    return args.length === 0 ? s : s.replace(/\{(\d)\}/g, (m, i) => (args[Number(i)] != null ? String(args[Number(i)]) : m));
}
