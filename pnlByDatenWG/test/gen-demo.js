// generates src/demo.ts from test/demo-data.js (pharma demo, mEUR → EUR).
// Run: node test/gen-demo.js   (test/demo-test.js fails when src/demo.ts is stale)
const path = require("path");
const ROOT = path.join(__dirname, "..");
global.window = {};
require("./demo-data.js");
const d = window.PNL_DEMO;
const NAME = {
  "Net revenue": "Revenue", "Pharmaceuticals (Rx)": "Rx", "Consumer Health": "Consumer",
  "Contract manufacturing": "Contract", "Cost of goods sold": "Cogs", "Materials": "Materials",
  "Production": "Production", "Other cost of sales": "OtherCos", "Gross profit": "GrossProfit",
  "Gross margin": "GrossMargin", "Operating expenses": "Opex", "Research & development": "RnD",
  "Selling & marketing": "Selling", "General & administration": "Admin",
  "Other operating result": "OtherOp", "License & milestone income": "License", "FX result": "Fx",
  "Other operating expenses": "OtherOpex", "EBITDA": "Ebitda", "EBITDA margin": "EbitdaMargin",
  "Depreciation & amortization": "DnA", "Depreciation sites & equipment": "Depr",
  "Amortization intangibles": "Amort", "EBIT": "Ebit", "EBIT margin": "EbitMargin",
  "Financial result": "FinResult", "Interest expense": "Interest",
  "Interest & investment income": "InterestInc", "EBT": "Ebt", "Income taxes": "Taxes",
  "Net income": "NetIncome", "Net margin": "NetMargin",
};
const acc = new Map();
for (const r of d.levelRows) {
  if (r.account === "999900") continue; // data-quality demo row stays in the harness only
  if (!acc.has(r.account)) acc.set(r.account, { r, m: {} });
  if (r.month) acc.get(r.account).m[r.month] = r.values;
}
const key = n => { if (!NAME[n]) throw new Error("no key for " + n); return NAME[n]; };
const out = [];
const sc = ["ac", "py", "pl"];
for (const [id, { r, m }] of acc) {
  const lv = r.levels.filter(x => x != null).map(key);
  const f = r.formulaDef ? r.formulaDef.replace(/\[([^\]]+)\]/g, (_, n) => "[@" + key(n) + "]") : null;
  const months = d.months.map(mm => m[mm]);
  const ser = {};
  if (months.some(Boolean)) {
    for (const s of sc) ser[s] = months.map(v => v && v[s] != null ? Math.round(v[s] * 10) : null);
  }
  const fy = months.find(Boolean);
  out.push(`    { id: ${JSON.stringify(id)}, levels: ${JSON.stringify(lv)}, sort: ${r.sort}, type: ${JSON.stringify(r.rowType)}, ` +
    `f: ${JSON.stringify(f)}, sign: ${r.sign}, disp: ${r.displayInvert}, varInv: ${r.varianceInvert}` +
    (ser.ac ? `,\n      ac: ${JSON.stringify(ser.ac)}, py: ${JSON.stringify(ser.py)}, pl: ${JSON.stringify(ser.pl)}` : "") +
    (fy && fy.fcfy != null ? `, fcfy: ${Math.round(fy.fcfy * 10)}, plfy: ${Math.round(fy.plfy * 10)}` : "") + " },");
}
const ts = `/*
 * Smart Start demo statement — the pharma demo of test/demo-data.js as compact
 * rows. GENERATED by test/gen-demo.js — do not edit by hand. Values are
 * tenths of a million EUR; buildDemoRows() turns them into EUR so the auto
 * scaling shows "mEUR". Level names and formula references are resource keys
 * (UI_DN_<key>) — the demo speaks the reader's language, formulas included.
 * Reconciliation (YTD AC): EBITDA 571.2 · EBIT 475.6 · EBT 458.8 · net income 339.5 mEUR.
 */
import { LevelInputRow, RowType } from "./engine";

export const DEMO_MONTHS = ${JSON.stringify(d.months)};

interface DemoRow {
    id: string; levels: string[]; sort: number; type: RowType; f: string | null;
    sign: number; disp: boolean; varInv: boolean;
    ac?: (number | null)[]; py?: (number | null)[]; pl?: (number | null)[];
    fcfy?: number; plfy?: number;
}

const ROWS: DemoRow[] = [
${out.join("\n")}
];

/**
 * The demo as level-input rows (one per account × month, formula rows once),
 * names resolved through \`name\` (resource key → localized text).
 */
export function buildDemoRows(name: (key: string) => string): LevelInputRow[] {
    const nm = (k: string): string => name("UI_DN_" + k);
    const rows: LevelInputRow[] = [];
    let index = 0;
    for (const r of ROWS) {
        const levels: (string | null)[] = [...r.levels.map(nm), null, null].slice(0, 3);
        const base = {
            levels, account: r.id, name: null, sort: r.sort, rowType: r.type,
            formulaDef: r.f == null ? null : r.f.replace(/\\[@([A-Za-z]+)\\]/g, (_m: string, k: string) => "[" + nm(k) + "]"),
            sign: r.sign, displayInvert: r.disp, varianceInvert: r.varInv, comment: null,
        };
        if (!r.ac) {
            rows.push({ ...base, values: {}, month: null, index: index++ });
            continue;
        }
        DEMO_MONTHS.forEach((m, i) => {
            const v = (a?: (number | null)[]): number | null => (a && a[i] != null ? a[i]! * 1e5 : null);
            rows.push({
                ...base, month: m, index: index++,
                values: {
                    ac: v(r.ac), py: v(r.py), pl: v(r.pl),
                    fcfy: r.fcfy != null ? r.fcfy * 1e5 : null, plfy: r.plfy != null ? r.plfy * 1e5 : null,
                },
            });
        });
    }
    return rows;
}
`;
if (process.argv[2] === "--print") { process.stdout.write(ts); }
else { require("fs").writeFileSync(path.join(ROOT, "src/demo.ts"), ts); console.log("demo rows", acc.size); }
