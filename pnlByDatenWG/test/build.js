/* eslint-disable powerbi-visuals/non-literal-fs-path -- build tooling, paths are fixed under the repo */
// bundles src/visual.ts for the browser harness (powerbi-visuals-api shimmed)
// and writes test/locales.js — the four resjson files as window.PNL_LOCALES, so
// the harness host can hand the visual a real localization manager
const esbuild = require("esbuild");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const LOCALES = {};
const resDir = path.join(ROOT, "stringResources");
for (const loc of fs.readdirSync(resDir)) {
    const f = path.join(resDir, loc, "resources.resjson");
    if (fs.existsSync(f)) { LOCALES[loc] = JSON.parse(fs.readFileSync(f, "utf8")); }
}
fs.writeFileSync(path.join(__dirname, "locales.js"),
    "// generated by test/build.js from stringResources/<locale>/resources.resjson\n" +
    "window.PNL_LOCALES = " + JSON.stringify(LOCALES) + ";\n");

esbuild.build({
    entryPoints: [path.join(ROOT, "src/visual.ts")],
    bundle: true,
    format: "iife",
    globalName: "PnlByDatenWG",
    outfile: path.join(__dirname, "visual.bundle.js"),
    loader: { ".less": "empty" },
    alias: { "powerbi-visuals-api": path.join(__dirname, "pbi-shim.js") },
    absWorkingDir: ROOT,
    tsconfigRaw: JSON.stringify({ compilerOptions: { experimentalDecorators: true } })
}).then(() => console.log("bundle ok")).catch(e => { console.error(e); process.exit(1); });
